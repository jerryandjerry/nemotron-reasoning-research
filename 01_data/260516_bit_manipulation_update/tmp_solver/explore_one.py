import sys

def b(x): return format(x & 0xFF, '08b')
def rotl(x,k): k%=8; return ((x<<k)|(x>>(8-k)))&0xFF if k else x&0xFF
def rotr(x,k): k%=8; return ((x>>k)|(x<<(8-k)))&0xFF if k else x&0xFF
def shl(x,k,f=0):
    if k>=8: return 0xFF if f else 0
    r=(x<<k)&0xFF
    if f: r|=(1<<k)-1
    return r
def shr(x,k,f=0):
    if k>=8: return 0xFF if f else 0
    r=x>>k
    if f: r|=((1<<k)-1)<<(8-k) & 0xFF
    return r&0xFF
def rev(x): return int(format(x&0xFF,'08b')[::-1],2)
def swap(x): return ((x<<4)|(x>>4))&0xFF

