UNARY = []
UNARY.append(("id", lambda x: x))
UNARY.append(("not", lambda x: (~x)&0xFF))
UNARY.append(("rev", rev))
UNARY.append(("swap", swap))
UNARY.append(("not_rev", lambda x: (~rev(x))&0xFF))
UNARY.append(("rev_not", lambda x: rev((~x)&0xFF)))
for k in range(1, 8):
    UNARY.append((f"rotl{k}", lambda x, k=k: rotl(x, k)))
    UNARY.append((f"rotr{k}", lambda x, k=k: rotr(x, k)))
    for f in (0,1):
        UNARY.append((f"shl{k}f{f}", lambda x, k=k, f=f: shl(x, k, f)))
        UNARY.append((f"shr{k}f{f}", lambda x, k=k, f=f: shr(x, k, f)))

OPS = [('^',lambda a,b:a^b),('&',lambda a,b:a&b),('|',lambda a,b:a|b),
       ('+',lambda a,b:(a+b)&0xFF),('-',lambda a,b:(a-b)&0xFF),
       ('andn1',lambda a,b:a & (~b)&0xFF), ('andn2',lambda a,b:(~a)&0xFF & b)]

def main():
    pid = sys.argv[1]
    pairs, q, gold = PUZZLES[pid]
    print(f"=== {pid} === query={b(q)} gold={b(gold)}")

    # Test all (u(x) op v(x)) ^ const
    matches = []
    for un, uf in UNARY:
        for vn, vf in UNARY:
            for on, of in OPS:
                fn = lambda x, uf=uf, vf=vf, of=of: of(uf(x), vf(x)) & 0xFF
                # check no constant
                if all(fn(x) == y for x, y in pairs):
                    matches.append((f"{un}{on}{vn}", fn))
                # check with xor constant
                x0, y0 = pairs[0]
                c = fn(x0) ^ y0
                if c != 0:
                    fn2 = lambda x, fn=fn, c=c: fn(x) ^ c
                    if all(fn2(x) == y for x, y in pairs):
                        matches.append((f"{un}{on}{vn}^{c:02x}", fn2))
    for n, fn in matches[:20]:
        pred = fn(q)
        tag = 'MATCH' if pred == gold else 'MISMATCH'
        print(f"  {tag} {n}: pred={b(pred)} gold={b(gold)}")
    print(f"  total {len(matches)} candidates")

if __name__ == '__main__':
    main()
